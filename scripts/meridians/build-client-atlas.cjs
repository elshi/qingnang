// Regenerate the picture index used with the pre-atlas WeChat backend.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const read = name => JSON.parse(fs.readFileSync(path.join(root, 'database/atlas', name), 'utf8'));
const graphics = read('graphics.json');
const atlas = {
  credit: graphics.credit,
  groups: graphics.groups,
  channels: read('channels.json').map(channel => ({ ...channel, plates: graphics.channels[channel.key] })),
  extras: read('extra-graphics.json')
};
const destination = path.join(root, 'miniprogram/utils/atlas-catalog.js');
fs.writeFileSync(destination, '// Generated by scripts/meridians/build-client-atlas.cjs\nmodule.exports = ' +
  JSON.stringify(atlas, null, 2) + ';\n');
